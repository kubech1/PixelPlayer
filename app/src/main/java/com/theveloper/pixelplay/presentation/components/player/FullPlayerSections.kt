@Composable
internal fun BottomToggleRow(
    modifier: Modifier,
    songId: String?,
    isShuffleEnabled: Boolean,
    isShuffleTransitionInProgress: Boolean,
    repeatMode: Int,
    isFavoriteProvider: () -> Boolean,
    onShuffleToggle: () -> Unit,
    onRepeatToggle: () -> Unit,
    onFavoriteToggle: () -> Unit
) {
    val isFavorite = isFavoriteProvider()
    val hapticFeedback = LocalHapticFeedback.current
    val rowCorners = 60.dp
    val inactiveBg = LocalMaterialTheme.current.onSurface.copy(alpha = 0.07f)
    val inactiveContentColor = LocalMaterialTheme.current.onSurface


    Box(
        modifier = modifier.playerGlass(
            tint = LocalMaterialTheme.current.surfaceContainerLowest,
            shape = AbsoluteSmoothCornerShape(
                cornerRadiusBL = rowCorners,
                smoothnessAsPercentTR = 60,
                cornerRadiusBR = rowCorners,
                smoothnessAsPercentBL = 60,
                cornerRadiusTL = rowCorners,
                smoothnessAsPercentBR = 60,
                cornerRadiusTR = rowCorners,
                smoothnessAsPercentTL = 60
            )
        )
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(6.dp),
            horizontalArrangement = Arrangement.spacedBy(6.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            val commonModifier = Modifier.weight(1f)

            ToggleSegmentButton(
                modifier = commonModifier,
                active = isShuffleEnabled,
                enabled = !isShuffleTransitionInProgress,
                activeColor = LocalMaterialTheme.current.primaryFixed,
                activeCornerRadius = rowCorners,
                activeContentColor = LocalMaterialTheme.current.onPrimaryFixed,
                inactiveColor = inactiveBg,
                inactiveContentColor = inactiveContentColor,
                onClick = {
                    hapticFeedback.performHapticFeedback(
                        if (isShuffleEnabled) HapticFeedbackType.ToggleOff else HapticFeedbackType.ToggleOn
                    )
                    onShuffleToggle()
                },
                iconId = R.drawable.rounded_shuffle_24,
                rotateOnActivation = true,
                inactiveCornerRadius = PlayerControlInnerCorner,
                inactiveStartCornerRadius = PlayerControlOuterCorner,
                contentDesc = androidx.compose.ui.res.stringResource(R.string.common_shuffle)
            )
            val repeatActive = repeatMode != Player.REPEAT_MODE_OFF
            val repeatIcon = when (repeatMode) {
                Player.REPEAT_MODE_ONE -> R.drawable.rounded_repeat_one_24
                Player.REPEAT_MODE_ALL -> R.drawable.rounded_repeat_24
                else -> R.drawable.rounded_repeat_24
            }
            ToggleSegmentButton(
                modifier = commonModifier,
                active = repeatActive,
                activeColor = LocalMaterialTheme.current.secondaryFixed,
                activeCornerRadius = rowCorners,
                activeContentColor = LocalMaterialTheme.current.onSecondaryFixed,
                inactiveColor = inactiveBg,
                inactiveContentColor = inactiveContentColor,
                onClick = {
                    hapticFeedback.performHapticFeedback(HapticFeedbackType.SegmentTick)
                    onRepeatToggle()
                },
                iconId = repeatIcon,
                crossfadeIcon = true,
                inactiveCornerRadius = PlayerControlInnerCorner,
                contentDesc = androidx.compose.ui.res.stringResource(R.string.common_repeat)
            )
            FavoriteButton(
                songId = songId,
                isFavorite = isFavorite,
                onToggle = onFavoriteToggle,
                modifier = commonModifier.fillMaxHeight(),
                shape = if (isFavorite) RoundedCornerShape(rowCorners) else InactiveFavoriteSegmentShape,
                containerColor = if (isFavorite) LocalMaterialTheme.current.tertiaryFixed else inactiveBg,
                contentColor = if (isFavorite) LocalMaterialTheme.current.onTertiaryFixed else inactiveContentColor,
                style = FavoriteButtonStyle.Full,
                palette = LocalMaterialTheme.current
            )
        }
    }
}
