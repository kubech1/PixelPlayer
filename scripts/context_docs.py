#!/usr/bin/env python3
"""Generate and check the repository's source-context indexes (Python stdlib only)."""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import hashlib
import os
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
SKIP_DIRS = {'.git', '.idea', '.gradle', '.kotlin', 'build', '__pycache__', 'node_modules'}
PRIVATE_FILES = {'local.properties', 'keystore.properties', '.env', 'google-services.json'}
CODE_SUFFIXES = {'.kt', '.kts', '.java', '.js', '.py', '.c', '.cc', '.cpp', '.h', '.hpp', '.proto', '.bat', '.sh', '.ps1'}
CODE_NAMES = {'gradlew', 'CMakeLists.txt'}
CONFIG_SUFFIXES = {'.xml', '.json', '.toml', '.properties', '.yml', '.yaml', '.pro', '.conf', '.svg'}
CONFIG_NAMES = {'.gitignore', 'baseline-prof.txt', 'startup-prof.txt'}
SYMBOL = re.compile(r'^\s*(?:(?:public|private|internal|protected|actual|expect|open|abstract|sealed|data|enum|annotation|value|inline|tailrec|suspend|override|const|external)\s+)*(?:class|interface|object|fun|def)\s+([\w.]+)')


def files():
    for directory, dirs, names in os.walk(ROOT):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not d.startswith('.venv'))
        for name in sorted(names):
            path = Path(directory) / name
            if name in PRIVATE_FILES or name.startswith('.env.') or path.is_symlink():
                continue
            yield path


def category(path: Path) -> str:
    relative = path.relative_to(ROOT).as_posix()
    if relative.startswith('scripts/'):
        return 'documentation-maintenance.md'
    if path.suffix == '.kts' or path.name in {'gradlew', 'gradlew.bat'}:
        return 'build-and-testing.md'
    if relative.startswith('baselineprofile/') or '/src/test/' in relative or '/src/androidTest/' in relative:
        return 'build-and-testing.md'
    if relative.startswith(('wear/', 'shared/')) or '/service/wear/' in relative:
        return 'wear-protocol.md'
    if '/data/diagnostics/' in relative:
        return 'diagnostics.md'
    if '/data/backup/' in relative or '/data/provider/' in relative:
        return 'backup-and-security.md'
    if any(segment in relative for segment in ('/data/ai/', '/data/stream/', '/data/network/', '/data/remote/', '/data/image/', '/data/telegram/', '/data/gdrive/', '/data/netease/', '/data/qqmusic/', '/data/navidrome/', '/data/jellyfin/', '/data/github/', '/service/cast/', '/service/http/')):
        return 'integrations.md'
    if '/data/service/' in relative or '/data/equalizer/' in relative:
        return 'playback.md'
    if '/presentation/' in relative or '/ui/' in relative:
        return 'ui-and-state.md'
    if '/data/' in relative or '/utils/' in relative:
        return 'library-and-data.md'
    return 'architecture.md'


def group(path: Path) -> str:
    relative = path.relative_to(ROOT)
    if relative.suffix in CODE_SUFFIXES:
        return relative.parent.as_posix()
    if '/res/' in relative.as_posix():
        return relative.parent.as_posix()
    return relative.parent.as_posix() or '.'


def build_index(selected: list[Path], title: str, include_symbols: bool) -> str:
    selected = sorted(selected, key=lambda p: p.relative_to(ROOT).as_posix())
    digest = hashlib.sha256()
    groups = defaultdict(list)
    for path in selected:
        relative = path.relative_to(ROOT).as_posix()
        digest.update(relative.encode('utf-8') + b'\0' + hashlib.sha256(path.read_bytes()).digest())
        groups[group(path)].append(path)
    lines = [f'# {title}', '', '<!-- GENERATED by scripts/context_docs.py; do not edit by hand. -->', '',
             'Regenerar desde la raíz: `python scripts/context_docs.py generate`.', '',
             f'Archivos: **{len(selected)}**. Huella de rutas y contenido: `{digest.hexdigest()}`.', '',
             'Este índice permite localizar archivos; no certifica su comportamiento ni sustituye los documentos temáticos. '
             'Los símbolos son una extracción léxica parcial, no un análisis del compilador. '
             'Se excluyen cachés, salidas de build, entornos virtuales y archivos locales de credenciales.', '',
             'Lectura inicial: [guía del proyecto](../README.md).', '', '## Resumen', '',
             '| Área | Archivos |', '| --- | ---: |']
    counts = Counter(path.relative_to(ROOT).parts[0] if len(path.relative_to(ROOT).parts) > 1 else '(raíz)' for path in selected)
    for area, count in sorted(counts.items()):
        lines.append(f'| `{area}` | {count} |')
    for folder, members in sorted(groups.items()):
        lines.extend(['', f'## {folder}', '', '| Archivo | Líneas | Orientación |' if include_symbols else '| Archivo | Líneas |',
                      '| --- | ---: | --- |' if include_symbols else '| --- | ---: |'])
        for path in members:
            relative = path.relative_to(ROOT).as_posix()
            body = path.read_text(encoding='utf-8-sig')
            label = f'[{path.name}](../../{relative})'
            row = f'| {label} | {len(body.splitlines())} |'
            if include_symbols:
                symbols = list(dict.fromkeys(match.group(1) for line in body.splitlines() if (match := SYMBOL.match(line))))[:6]
                detail = ', '.join(f'`{name}`' for name in symbols) or 'Sin declaración extraída'
                row += f' [{category(path).removesuffix(".md")}](../{category(path)}) · {detail} |'
            lines.append(row)
    return '\n'.join(lines) + '\n'


def expected_indexes():
    paths = list(files())
    code = [p for p in paths if p.suffix in CODE_SUFFIXES or p.name in CODE_NAMES]
    config = [p for p in paths if p.suffix in CONFIG_SUFFIXES or p.name in CONFIG_NAMES]
    return {
        ROOT / 'docs/reference/source-index.md': build_index(code, 'Índice de código', True),
        ROOT / 'docs/reference/config-index.md': build_index(config, 'Índice de configuración y recursos textuales', False),
    }


def markdown_links(document: Path):
    body = document.read_text(encoding='utf-8')
    body = re.sub(r'^```.*?^```\s*$', '', body, flags=re.MULTILINE | re.DOTALL)
    for match in re.finditer(r'!?\[[^\]\n]*\]\(([^)\n]+)\)', body):
        target = match.group(1).strip()
        if target.startswith('<'):
            target = target[1:target.index('>')]
        else:
            target = target.split(' "', 1)[0]
        parsed = urlsplit(target)
        if parsed.scheme or target.startswith('//') or not parsed.path:
            continue
        path = (document.parent / unquote(parsed.path)).resolve()
        yield path


def check(indexes) -> list[str]:
    errors = []
    for target, expected in indexes.items():
        if not target.is_file() or target.read_text(encoding='utf-8') != expected:
            errors.append(f'Índice desactualizado: {target.relative_to(ROOT)}; ejecuta generate.')
    documents = [ROOT / 'AGENTS.md', ROOT / 'README.md', *sorted((ROOT / 'docs').rglob('*.md'))]
    for document in documents:
        if not document.is_file():
            errors.append(f'Falta documento: {document.relative_to(ROOT)}')
            continue
        for path in markdown_links(document):
            if not path.exists():
                errors.append(f'Enlace local roto en {document.relative_to(ROOT)}: {path}')
    agents = ROOT / 'AGENTS.md'
    if agents.exists() and agents.stat().st_size > 16_384:
        errors.append('AGENTS.md supera el presupuesto local de 16 KiB; mueve detalle a docs/.')
    required = ['README.md', 'architecture.md', 'library-and-data.md', 'playback.md', 'ui-and-state.md',
                'integrations.md', 'wear-protocol.md', 'backup-and-security.md', 'diagnostics.md',
                'build-and-testing.md', 'documentation-maintenance.md', 'documentation-audit.md',
                'context-design.md', 'decisions/0001-context-structure.md']
    for name in required:
        if not (ROOT / 'docs' / name).is_file():
            errors.append(f'Falta tema requerido: docs/{name}')
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['generate', 'check'])
    args = parser.parse_args()
    indexes = expected_indexes()
    if args.command == 'generate':
        for path, body in indexes.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body, encoding='utf-8', newline='\n')
            print(f'Generado: {path.relative_to(ROOT)}')
        return 0
    errors = check(indexes)
    for error in errors:
        print(error, file=sys.stderr)
    if errors:
        return 1
    print('OK: índices de código/configuración vigentes, enlaces locales válidos y temas requeridos presentes.')
    print('Comprobación estructural; no demuestra exactitud semántica, compilación Android ni conformidad de un agente.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
